import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {readFile} from 'node:fs/promises';

const origin=process.env.GDT_TEST_ORIGIN || 'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true});
try{
 for(const viewport of [{width:2560,height:1440},{width:390,height:844}]){
  const page=await browser.newPage({viewport});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.stack || error.message));
  await page.goto(origin+'/validator/index.html');
  await page.locator('#preset').selectOption('inventory');
  await page.locator('#validate').click();
  assert.match(await page.locator('#status').innerText(),/Structurally valid/);
  await page.locator('#handlers').fill('inventory.select\ninventory.equip\ninventory.search\ninventory.sort');
  await page.locator('#data').fill(JSON.stringify({inventory:{items:[],search:'',selected:{name:'Sword',description:'Item'}}}));
  await page.locator('#validate').click();
  assert.match(await page.locator('#status').innerText(),/validation passed|integration warnings/i);
  await page.goto(origin+'/layout-kit/example/index.html');
  const buttons=page.locator('[data-node-id="item_grid"] button');
  assert.equal(await buttons.count(),3);
  await buttons.first().click();
  assert.match(await page.locator('#last-event').innerText(),/inventory.select/);
  await page.locator('#screen').selectOption('settings');
  await page.locator('[data-node-id="music_toggle"] input').uncheck();
  assert.match(await page.locator('#last-event').innerText(),/settings.music_changed/);
  await page.goto(origin+'/layout-kit/behaviors-demo/index.html');
  assert.equal(await page.locator('[data-node-id="item_grid"] button').count(),6);
  await page.locator('[data-node-id="item_grid"] button').filter({hasText:'Travel shield'}).click();
  assert.match(await page.locator('#state').innerText(),/item-02/);
  await page.locator('[data-node-id="search_items"]').fill('shield');
  await page.locator('[data-node-id="search_items"]').dispatchEvent('change');
  assert.equal(await page.locator('[data-node-id="item_grid"] button').count(),1);
  await page.locator('[data-node-id="equip"]').click();
  assert.match(await page.locator('#events').innerText(),/inventory.equip/);
  await page.locator('[data-screen="equipment"]').click();
  assert.match(await page.locator('#state').innerText(),/Travel shield/);
  await page.locator('[data-screen="shop"]').click();
  await page.locator('[data-node-id="buy"]').click();
  assert.match(await page.locator('#state').innerText(),/shop.purchase/);
  await page.locator('#cancel-confirm').click();
  assert.doesNotMatch(await page.locator('#state').innerText(),/"pendingAction": "shop.purchase"/);
  await page.locator('[data-node-id="buy"]').click();
  await page.locator('#approve-confirm').click();
  assert.match(await page.locator('#events').innerText(),/shop.purchase/);
  await page.locator('[data-node-id="buy"]').click();
  await page.keyboard.press('Escape');
  assert.doesNotMatch(await page.locator('#state').innerText(),/"pendingAction": "shop.purchase"/);
  await page.goto(origin+'/catalog/index.html?preset=garage');
  assert.match(await page.locator('#name').innerText(),/Garage/);
  await page.locator('#category').selectOption('racing');
  assert.match(await page.locator('#count').innerText(),/3 templates/);
  await page.locator('#search').fill('dealership');
  assert.match(await page.locator('#count').innerText(),/1 templates/);
  await page.locator('.template').first().click();
  assert.match(await page.locator('#name').innerText(),/Dealership/);
  assert.match(await page.locator('#actions').innerText(),/dealership.purchase_request/);
  await page.goto(origin+'/builder/index.html?preset=crafting');
  assert.match(await page.locator('#count').innerText(),/11 controls/);
  assert.equal(await page.locator('#template').inputValue(),'crafting');
  await page.locator('#preview').click();
  assert.ok(await page.locator('[data-node-id="recipes"] button').count()>0);
  await page.locator('[data-node-id="craft"]').click();
  assert.match(await page.locator('#event-output').innerText(),/crafting.craft_request/);
  await page.goto(origin+'/validator/index.html?preset=race-selection');
  assert.equal(await page.locator('#preset').inputValue(),'race-selection');
  assert.match(await page.locator('#status').innerText(),/Structurally valid/);
  await page.goto(origin+'/package/index.html?preset=inventory');
  assert.match(await page.locator('#selected-count').innerText(),/1 selected/);
  await page.locator('#search').fill('settings');
  await page.locator('.template-entry input[value="settings"]').check();
  assert.match(await page.locator('#selected-count').innerText(),/2 selected/);
  assert.match(await page.locator('#action-count').innerText(),/^[1-9]/);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  const packageDownload=await downloadPromise;
  assert.match(packageDownload.suggestedFilename(),/gdt-ui-web-2-templates\.zip/);
  const zipBytes=await readFile(await packageDownload.path());
  assert.equal(zipBytes.readUInt32LE(0),0x04034b50);
  assert.ok(zipBytes.includes(Buffer.from('contracts/inventory.contract.json')));
  assert.ok(zipBytes.includes(Buffer.from('CODEX_INTEGRATION.md')));
  await page.goto(origin+'/builder/index.html?preset=garage');
  await page.locator('#package-current').click();
  await page.waitForURL('**/package/index.html');
  assert.match(await page.locator('#selected-count').innerText(),/1 selected/);
  await page.goto(origin+'/builder/index.html?preset=skill-tree');
  assert.equal(await page.locator('.wf-edges line').count(),4);
  assert.ok(await page.locator('.wf-node[data-shape="circle"]').count()>=5);
  await page.locator('#connect-mode').click();
  await page.locator('.wf-node[data-id="skill_final_left"]').click();
  await page.locator('.wf-node[data-id="skill_final_right"]').click();
  assert.equal(await page.locator('.wf-edges line').count(),5);
  await page.locator('#connect-mode').click();
  await page.locator('.wf-node[data-id="skill_root"]').click();
  await page.locator('#prop-shape').selectOption('rounded');
  assert.equal(await page.locator('.wf-node[data-id="skill_root"]').getAttribute('data-shape'),'rounded');
  await page.locator('#undo').click();
  assert.equal(await page.locator('.wf-node[data-id="skill_root"]').getAttribute('data-shape'),'circle');
  await page.locator('#preview').click();
  assert.equal(await page.locator('.gdt-connections line').count(),5);
  await page.locator('[data-node-id="skill_right"]').click();
  assert.match(await page.locator('#event-output').innerText(),/skills.select_node/);
  await page.goto(origin+'/catalog/index.html?preset=skill-tree');
  assert.equal(await page.locator('.gdt-connections line').count(),4);
  await page.goto(origin+'/builder/index.html');
  await page.locator('#template').selectOption('inventory');
  assert.match(await page.locator('#count').innerText(),/9 controls/);
  await page.locator('#preview').click();
  await page.locator('[data-node-id="equip"]').click();
  assert.match(await page.locator('#event-output').innerText(),/inventory.equip/);
  assert.deepEqual(errors,[], 'Unexpected browser JavaScript errors at viewport '+viewport.width);
  await page.close();
 }
 console.log('Browser smoke tests passed at desktop 1440p and mobile viewport.');
} finally {await browser.close();}
